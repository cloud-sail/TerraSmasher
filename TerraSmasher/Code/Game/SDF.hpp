enum class SDFFillMethod
{
	UNIFORM_BLEND,		// use matID1, matID2, blendValue
	Z_AXIS_GRADIENT,	// matID1 is at the bottom, matID2 is at the top, 
						// minZ factor(0.9), maxZ factor(0.95), Smooth step, e.g. grass on the soil
	DISTANCE_GRADIENT,	// matID1 is inside, matID2 is outside, minDist = -2.0f maxDist = -1.0f, Smooth Step
						// e.g. a watermelon 
};

