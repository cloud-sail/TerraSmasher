class SDF
{
protected:
	GameTransform m_transform;
public:
	bool m_isPointCloud = false;

protected:
	virtual float ComputeLocalSDF(Vec3 const& localPos) const = 0;

	virtual AABB3 ComputeLocalAABB() const = 0;

public:
	virtual ~SDF() = default;
	virtual const char* GetShapeName() const = 0;
	virtual void AddWorldVerts(std::vector<Vertex_PCU>& worldVerts, Rgba8 const& color = Rgba8::OPAQUE_WHITE) const = 0;

	virtual AABB3 GetAffectedAABB() const; // bounding box for voxel sdf

	// Point Cloud is Generated By SDF, but no sdf definition here
	virtual uint8_t GetPointCloudDensity(Vec3 const& worldPos) const; 

	float GetSignedDistance(Vec3 const& worldPos) const;
	GameTransform& GetMutTransform() { return m_transform; }
	GameTransform const& GetTransform() const { return m_transform; }

	// XML Serialization
	virtual void WritePropertiesToXml(XmlElement& element) const = 0;
	virtual void ReadPropertiesFromXml(XmlElement const& element) = 0;
	virtual const char* GetTypeString() const = 0;
};

